/** @param {{model: any, modelPath: string, claimPath: string, reproduces: any}} args */
function banner({ model, modelPath, claimPath, reproduces }) {
  const meta = model.model ?? {};
  const lines = [
    '// ---------------------------------------------------------------------------',
    `// ${[meta.unit_id, meta.type, meta.class].filter(Boolean).join('  ·  ')}`,
    '//',
    `// Generated by yarn sync from ${modelPath}.`,
    `// The claim it closes: ${claimPath}`,
    '//',
    '// Every constant, every section count and every structural choice below is',
    "// the model's. The difference equations are the ordinary realisations of the",
    "// sections the model names — this site's arithmetic, not a measurement.",
  ];
  const domain = reproduces?.domain;
  if (domain) {
    if (domain.settings && Object.keys(domain.settings).length > 0) {
      lines.push('//', '// Compared against the unit over:');
      for (const [key, value] of Object.entries(domain.settings)) {
        lines.push(`//   ${key}: ${flatten(value)}`);
      }
    }
    if (Array.isArray(domain.stimulus) && domain.stimulus.length > 0) {
      lines.push(`//   stimulus: ${domain.stimulus.join(', ')}`);
    }
    if (typeof domain.outside === 'string') {
      lines.push('//', ...wrap(`Outside that domain this says nothing: ${domain.outside}`, '// '));
    }
  }
  const residual = reproduces?.residual;
  if (residual && typeof residual.median === 'number') {
    lines.push(
      '//',
      `// Residual: ${residual.median} median, ${residual.worst} worst, in ${residual.unit}.`,
    );
  }
  lines.push('// ---------------------------------------------------------------------------');
  return lines.join('\n');
}

/** @param {any} value */
function flatten(value) {
  if (Array.isArray(value)) return value.map(flatten).join(', ');
  if (value && typeof value === 'object') {
    return Object.entries(value)
      .map(([key, held]) => `${key} ${flatten(held)}`)
      .join('; ');
  }
  return String(value);
}

/**
 * Wrap prose to something a terminal can hold.
 *
 * Eighty-eight rather than the usual eighty: the tables in these files run to
 * two hundred characters and the block scrolls anyway, so a comment set to a
 * third of the width the code beside it takes reads as a different document.
 * @param {string} text @param {string} prefix
 */
function wrap(text, prefix, width = 88) {
  /** @type {string[]} */
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if (line && `${line} ${word}`.length > width) {
      lines.push(prefix + line);
      line = word;
    } else {
      line = line ? `${line} ${word}` : word;
    }
  }
  if (line) lines.push(prefix + line);
  return lines;
}

