/** `roland-sc8850-01` → `roland_sc8850_01`; `01 20` → `type_01_20`. */
function identifier(text) {
  return String(text)
    .trim()
    .replace(/[^0-9A-Za-z]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .replace(/^(\d)/, '_$1');
}

/** The namespace an example lives in, so two types can be included together. */
function namespaceOf(model) {
  const meta = model.model ?? {};
  const parts = ['soundings'];
  if (meta.unit_id) parts.push(identifier(meta.unit_id));
  if (meta.type) parts.push(`type_${bare(meta.type)}`);
  else if (meta.class) parts.push(identifier(meta.class));
  return parts.join('::');
}

/** The same without the leading-digit guard, for use after a prefix. */
function bare(text) {
  return String(text)
    .trim()
    .replace(/[^0-9A-Za-z]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

/** `40 03 03` → `b40_03_03`, which is what the byte is called in the code. */
function byteName(address) {
  return `b${bare(address)}`;
}

/** `corner_hz` → `CornerHz`. */
function camel(text) {
  return String(text)
    .split(/[^0-9A-Za-z]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

