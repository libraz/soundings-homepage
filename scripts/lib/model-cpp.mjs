/** @param {{model: any, modelPath: string, claimPath: string, reproduces: any}} args */
function lti(args) {
  const { model } = args;
  const chain = model.chain;
  if (!Array.isArray(chain) || chain.length === 0) throw new Error('the model has no chain');
  if (typeof model.sample_rate_hz !== 'number') {
    throw new Error('the model names no sample rate, and every section here is clocked by one');
  }
  for (const stage of chain) {
    if (!STAGES.has(stage.kind)) {
      throw new Error(
        `the chain holds a ${JSON.stringify(stage.kind)} section, which has no realisation here`,
      );
    }
  }

  /** @type {{name: string, address: string}[]} */
  const bytes = [];
  /** @type {string[]} */
  const maps = [];
  /** @type {Set<string>} */
  const helpers = new Set();
  let cmath = true; // every realisation here needs tan or exp

  /** One parameter: a constant, or a function of a byte. */
  const parameter = (stage, index, key) => {
    const value = stage[key];
    if (typeof value === 'number') return { constant: num(value) };
    if (value && typeof value === 'object' && typeof value.fixed === 'number') {
      return { constant: num(value.fixed), why: value.why ?? null };
    }
    if (value && typeof value === 'object' && value.map) {
      const why = unreadable(value.map);
      if (why) throw new Error(`${stage.kind}.${key} carries ${why}`);
      const name = `${stage.kind.replace(/-\w/g, (m) => m[1].toUpperCase())}${index}${camel(key)}`;
      maps.push(asCpp(value.map, name));
      if (needsCmath(value.map)) cmath = true;
      if (value.byte && !bytes.some((entry) => entry.address === value.byte)) {
        bytes.push({ name: byteName(value.byte), address: value.byte });
      }
      return { call: `${name}(${value.byte ? byteName(value.byte) : 'byte'})` };
    }
    return null;
  };

  /** @type {string[]} */
  const members = [];
  /** @type {string[]} */
  const prepare = [];
  /** @type {string[]} */
  const process = [];

  chain.forEach((stage, index) => {
    switch (stage.kind) {
      case 'allpass-chain':
        helpers.add('allpass').add('dcblock');
        allpassStage({ stage, index, parameter, members, prepare, process });
        break;
      case 'pole':
        helpers.add('onepole');
        poleStage({ stage, index, parameter, members, prepare, process });
        break;
      case 'shelf':
        helpers.add(stage.order === 2 ? 'biquad' : 'shelf1');
        shelfStage({ stage, index, parameter, members, prepare, process });
        break;
      case 'peaking':
        helpers.add('biquad');
        peakingStage({ stage, index, parameter, members, prepare, process });
        break;
      case 'gain':
        gainStage({ stage, index, parameter, members, prepare, process });
        break;
      default:
        throw new Error(`no realisation for ${stage.kind}`);
    }
  });

  const ns = namespaceOf(model);
  const rate = num(model.sample_rate_hz);
  const out = [banner(args), ''];
  if (cmath) out.push('#include <cmath>', '');
  out.push(`namespace ${ns} {`, '');
  if (typeof model.why_this_rate === 'string') {
    out.push(...wrap(model.why_this_rate, '// '));
  }
  out.push(`constexpr double kSampleRateHz = ${rate};`);
  out.push(PI, '');
  for (const helper of ['allpass', 'dcblock', 'onepole', 'shelf1', 'biquad']) {
    if (helpers.has(helper)) out.push(HELPERS[helper], '');
  }
  for (const map of maps) out.push(map, '');
  out.push('/** The chain the model names, in the order it names it. */');
  out.push('struct Effect {');
  out.push(...members.map((line) => `  ${line}`));
  out.push('');
  out.push(`  void prepare(${bytes.map((entry) => `int ${entry.name}`).join(', ') || 'void'}) {`);
  out.push(...prepare.map((line) => `    ${line}`));
  out.push('  }');
  out.push('');
  out.push('  double process(double x) {');
  out.push(...process.map((line) => `    ${line}`));
  out.push('    return x;');
  out.push('  }');
  out.push('};');
  out.push('');
  out.push(`}  // namespace ${ns}`);
  return out.join('\n');
}

/** @param {any} args */
function allpassStage({ stage, index, parameter, members, prepare, process }) {
  if (stage.feedback_around || stage.feedback_sections) {
    throw new Error(
      'the loop is taken around part of the cascade, and where it is tapped decides what the ' +
        'effect is — no example is printed from a tap point this file would have to guess',
    );
  }
  const sections = stage.sections;
  if (typeof sections !== 'number') throw new Error('the all-pass chain names no section count');
  const corner = parameter(stage, index, 'corner_hz');
  const mix = parameter(stage, index, 'mix');
  if (!corner || !mix) throw new Error('the all-pass chain names no corner or no mix');
  const feedback = stage.feedback === undefined ? null : parameter(stage, index, 'feedback');
  if (stage.feedback !== undefined && !feedback) {
    throw new Error('the all-pass chain carries a feedback the map reader could not read');
  }
  if (stage.q)
    throw new Error(
      'an all-pass section with a Q is a second-order one, which has no realisation here',
    );

  members.push(`Allpass1 allpass${index}[${sections}];`);
  members.push(`double mix${index} = 0.0;`);
  if (feedback) {
    members.push(`double feedback${index} = 0.0;`);
    members.push(`double loop${index} = 0.0;`);
    members.push(`DcBlock block${index};`);
  }

  prepare.push(`const double corner${index} = ${corner.call ?? corner.constant};`);
  prepare.push(`for (Allpass1& section : allpass${index}) section.setCornerHz(corner${index});`);
  prepare.push(`mix${index} = ${mix.call ?? mix.constant};`);
  if (feedback) {
    prepare.push(`feedback${index} = ${feedback.call ?? feedback.constant};`);
    if (typeof stage.feedback_highpass_hz === 'number') {
      prepare.push(`block${index}.setCornerHz(${num(stage.feedback_highpass_hz)});`);
    }
  }

  if (feedback) {
    const delay = stage.feedback_delay ?? 0;
    if (delay !== 1) {
      throw new Error(
        `the loop is ${delay} sample(s) late, and only a one-sample loop has a realisation here`,
      );
    }
    process.push('// The loop returns one sample late and through a block at DC, which is what');
    process.push('// the model names. The cascade is summed with the dry, never averaged with it.');
    process.push(
      `double wet${index} = x + feedback${index} * block${index}.process(loop${index});`,
    );
  } else {
    process.push(`double wet${index} = x;`);
  }
  process.push(
    `for (Allpass1& section : allpass${index}) wet${index} = section.process(wet${index});`,
  );
  if (feedback) process.push(`loop${index} = wet${index};`);
  process.push(`x = x + mix${index} * wet${index};`);
}

/** @param {any} args */
function poleStage({ stage, index, parameter, members, prepare, process }) {
  if (stage.q) {
    throw new Error(
      'a pole with a Q is a conjugate pair rather than a single pole, and no example is printed ' +
        'from one here',
    );
  }
  const side = stage.side;
  if (side !== 'low' && side !== 'high') throw new Error(`a pole on side ${JSON.stringify(side)}`);
  // A model that names no form means the ordinary bilinear-transformed pole: the
  // archive's own catalogue holds the cheap one as a separate candidate, under
  // its own name, so the unqualified reading is not ambiguous.
  const form = stage.form ?? 'bilinear';
  if (form !== 'bilinear' && form !== 'one-multiply') {
    throw new Error(`a pole written in the ${JSON.stringify(form)} form`);
  }
  const corner = parameter(stage, index, 'corner_hz');
  const sections = parameter(stage, index, 'sections');
  if (!corner || !sections) throw new Error('the pole names no corner or no section count');

  const cap = 8;
  members.push(`OnePole pole${index}[${cap}];`);
  members.push(`int poleCount${index} = 0;`);
  prepare.push(`poleCount${index} = static_cast<int>(${sections.call ?? sections.constant});`);
  prepare.push(`if (poleCount${index} > ${cap}) poleCount${index} = ${cap};`);
  prepare.push(`const double poleCorner${index} = ${corner.call ?? corner.constant};`);
  prepare.push(`for (int i = 0; i < poleCount${index}; ++i) {`);
  prepare.push(
    `  pole${index}[i].set(poleCorner${index}, OnePole::Side::${side === 'low' ? 'Low' : 'High'}, OnePole::Form::${form === 'one-multiply' ? 'OneMultiply' : 'Bilinear'});`,
  );
  prepare.push('}');
  process.push(`for (int i = 0; i < poleCount${index}; ++i) x = pole${index}[i].process(x);`);
}

/** @param {any} args */
function shelfStage({ stage, index, parameter, members, prepare, process }) {
  const side = stage.side;
  if (side !== 'low' && side !== 'high') throw new Error(`a shelf on side ${JSON.stringify(side)}`);
  const order = stage.order;
  if (order !== 1 && order !== 2) throw new Error(`a shelf of order ${JSON.stringify(order)}`);
  const corner = parameter(stage, index, 'corner_hz');
  const gain = parameter(stage, index, 'gain_db');
  if (!corner || !gain) throw new Error('the shelf names no corner or no gain');

  if (order === 1) {
    members.push(`Shelf1 shelf${index};`);
    prepare.push(
      `shelf${index}.set(${corner.call ?? corner.constant}, ${gain.call ?? gain.constant}, Shelf1::Side::${side === 'low' ? 'Low' : 'High'});`,
    );
    process.push(`x = shelf${index}.process(x);`);
    return;
  }
  members.push(`Biquad shelf${index};`);
  prepare.push(
    `shelf${index}.setShelf(${corner.call ?? corner.constant}, ${gain.call ?? gain.constant}, Biquad::Side::${side === 'low' ? 'Low' : 'High'});`,
  );
  process.push(`x = shelf${index}.process(x);`);
}

/** @param {any} args */
function peakingStage({ stage, index, parameter, members, prepare, process }) {
  const centre = parameter(stage, index, 'centre_hz');
  const gain = parameter(stage, index, 'gain_db');
  const q = parameter(stage, index, 'q');
  if (!centre || !gain || !q) throw new Error('the peaking section names no centre, gain or Q');
  members.push(`Biquad peaking${index};`);
  prepare.push(
    `peaking${index}.setPeaking(${centre.call ?? centre.constant}, ${gain.call ?? gain.constant}, ${q.call ?? q.constant});`,
  );
  process.push(`x = peaking${index}.process(x);`);
}

/** @param {any} args */
function gainStage({ stage, index, parameter, members, prepare, process }) {
  const gain = parameter(stage, index, 'gain_db');
  if (!gain) throw new Error('the gain section names no gain');
  members.push(`double gain${index} = 1.0;`);
  prepare.push(`gain${index} = std::pow(10.0, (${gain.call ?? gain.constant}) / 20.0);`);
  process.push(`x *= gain${index};`);
}

