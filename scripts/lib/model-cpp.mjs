/**
 * The byte at an address, and what it stands for.
 *
 * Several classes closed on a table rather than on a chain: a delay time, a
 * modulation rate, a rotor's acceleration. For those the table *is* the
 * algorithm, and which of several tables applies is chosen by the range the
 * document prints against the address — so the example carries the printed range
 * as the key, exactly as the archive does.
 * @param {{model: any, modelPath: string, claimPath: string, reproduces: any}} args
 */
function tables(args) {
  const { model } = args;
  const held = model.tables;
  if (!held || typeof held !== 'object' || Object.keys(held).length === 0) {
    throw new Error('the model holds no tables');
  }

  const ns = namespaceOf(model);
  const out = [banner(args), ''];
  let cmath = false;
  /** @type {string[]} */
  const functions = [];
  /** @type {[string, string][]} */
  const dispatch = [];

  for (const [range, table] of Object.entries(held)) {
    const why = unreadable(table);
    if (why) throw new Error(`the table printed against ${JSON.stringify(range)} is ${why}`);
    const name = `at${camel(identifier(range))}`;
    functions.push(`// printed range: ${range}`);
    if (typeof table.why_it_ends_early === 'string') {
      functions.push(...wrap(table.why_it_ends_early, '// '));
    }
    functions.push(asCpp(table, name));
    functions.push('');
    if (needsCmath(table)) cmath = true;
    dispatch.push([range, name]);
  }

  if (cmath) out.push('#include <cmath>', '');
  out.push('#include <cstring>', '');
  out.push(`namespace ${ns} {`, '');
  if (typeof model.what === 'string') out.push(...wrap(model.what, '// '), '');
  out.push(...functions);

  out.push('/**');
  out.push(' * Which table applies is decided by the range the page prints against the');
  out.push(' * address, which is a fact about the document rather than about the byte.');
  out.push(' */');
  out.push('inline bool lookUp(const char* printedRange, int byte, double& out) {');
  for (const [range, name] of dispatch) {
    out.push(
      `  if (std::strcmp(printedRange, ${JSON.stringify(range)}) == 0) { out = ${name}(byte); return true; }`,
    );
  }
  out.push('  // A range no reading has been taken over. Saying nothing is the answer:');
  out.push('  // returning a neighbouring table would be inventing a measurement.');
  out.push('  return false;');
  out.push('}');

  const arrival = model.arrival;
  if (arrival && typeof arrival === 'object') {
    out.push('');
    out.push('// The model also records where the quantity comes to rest, as figures rather');
    out.push('// than as a rule: what it is that reaches them is stated in the claim and is');
    out.push('// not written out here, because the condition is not in the model file.');
    for (const [key, value] of Object.entries(arrival)) {
      if (typeof value === 'number') {
        out.push(`inline constexpr double k${camel(key)} = ${num(value)};`);
      } else if (typeof value === 'string') {
        out.push(`// ${key}: ${value}`);
      }
    }
  }

  out.push('');
  out.push(`}  // namespace ${ns}`);
  return out.join('\n');
}
