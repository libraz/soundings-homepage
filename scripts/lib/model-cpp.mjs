/**
 * A model printed as C++.
 *
 * The archive keeps a closed claim's model as a small declarative file: a chain
 * of named sections, a sample rate, and one map per parameter byte. This turns
 * that into code a reader can compile, and it is a rearrangement of the model in
 * exactly the sense the rest of this site is a rearrangement of the archive —
 * every constant, every section count and every structural choice below comes
 * out of the model file and nothing is added to it.
 *
 * **What is not the model's is the arithmetic.** The archive names its sections
 * in the words of the era it is reading — a first-order all-pass, a one-multiply
 * pole, the unit-slope shelving biquad of the audio cookbook — and says nothing
 * about how to write their difference equations, because that is not a fact
 * about the unit. The realisations here are the ordinary ones for the sections
 * named. The generated banner says so, on every example, so that a reader never
 * has to guess which half of the file a measurement stands behind.
 *
 * **A model whose shape this file does not know prints nothing.** Not a partial
 * chain, not a section left out with a comment where it was: a chain missing one
 * stage is a different effect, and an example that quietly dropped one would be
 * the site asserting something no record establishes. The reason is returned
 * instead, and the page shows the reason.
 */

import { asCpp, needsCmath, num, unreadable } from './model-maps.mjs';

/** Stage kinds with a realisation here. */
const STAGES = new Set(['allpass-chain', 'pole', 'shelf', 'peaking', 'gain']);

/**
 * One model as C++, or the reason there is none.
 *
 * @param {object} args
 * @param {any} args.model the parsed model file
 * @param {string} args.modelPath its path in the archive
 * @param {string} args.claimPath the inference file whose claim it closes
 * @param {any} args.reproduces that inference's `reproduces` block
 * @returns {{code: string} | {unsupported: string}}
 */
export function asExample({ model, modelPath, claimPath, reproduces }) {
  const kind = model?.model?.kind ?? null;
  try {
    if (kind === 'lti') return { code: lti({ model, modelPath, claimPath, reproduces }) };
    if (kind === 'table') return { code: tables({ model, modelPath, claimPath, reproduces }) };
    return {
      unsupported: `the model is of kind ${JSON.stringify(kind)}, which no example is generated from yet`,
    };
  } catch (error) {
    return { unsupported: error.message };
  }
}

