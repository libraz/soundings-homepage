/** Not every standard library defines M_PI, and this file has to compile where it lands. */
const PI = 'constexpr double kPi = 3.14159265358979323846;';

const HELPERS = {
  allpass: `/**
 * One first-order all-pass section: unit gain at every frequency, and a phase
 * that runs from nothing to half a turn through the corner. Bilinear-transformed,
 * so the corner is prewarped and sits where it is asked for.
 */
struct Allpass1 {
  double a = 0.0, x1 = 0.0, y1 = 0.0;

  void setCornerHz(double hz) {
    const double k = std::tan(kPi * hz / kSampleRateHz);
    a = (k - 1.0) / (k + 1.0);
  }

  double process(double x) {
    const double y = a * x + x1 - a * y1;
    x1 = x;
    y1 = y;
    return y;
  }
};`,

  dcblock: `/** A one-pole high-pass, which is what blocking a loop at DC comes to. */
struct DcBlock {
  double r = 0.0, x1 = 0.0, y1 = 0.0;

  void setCornerHz(double hz) { r = std::exp(-2.0 * kPi * hz / kSampleRateHz); }

  double process(double x) {
    const double y = x - x1 + r * y1;
    x1 = x;
    y1 = y;
    return y;
  }
};`,

  onepole: `/**
 * A single pole, written either of the two ways the archive tells apart.
 *
 * \`Bilinear\` is the transformed pole, which carries a zero at half the rate.
 * \`OneMultiply\` is the cheapest a fixed-point part can write one — one multiply,
 * one state, and no zero — and the archive holds the two as separate candidates
 * because their skirts differ where it can read them.
 */
struct OnePole {
  enum class Side { Low, High };
  enum class Form { Bilinear, OneMultiply };

  Side side = Side::Low;
  Form form = Form::Bilinear;
  double a = 0.0, c = 0.0, k = 0.0, x1 = 0.0, y1 = 0.0, state = 0.0;

  void set(double hz, Side which, Form how) {
    side = which;
    form = how;
    if (how == Form::OneMultiply) {
      k = 1.0 - std::exp(-2.0 * kPi * hz / kSampleRateHz);
      return;
    }
    const double t = std::tan(kPi * hz / kSampleRateHz);
    c = (1.0 - t) / (1.0 + t);
    a = which == Side::Low ? t / (1.0 + t) : 1.0 / (1.0 + t);
  }

  double process(double x) {
    if (form == Form::OneMultiply) {
      state += k * (x - state);
      return side == Side::Low ? state : x - state;
    }
    const double y = side == Side::Low ? a * (x + x1) + c * y1 : a * (x - x1) + c * y1;
    x1 = x;
    y1 = y;
    return y;
  }
};`,

  shelf1: `/**
 * A first-order shelf: one pole, one zero, tilting the two sides of its corner
 * against each other. \`(s + w0 * V) / (s + w0)\` for a low shelf and
 * \`(V * s + w0) / (s + w0)\` for a high one, bilinear-transformed.
 */
struct Shelf1 {
  enum class Side { Low, High };

  double b0 = 1.0, b1 = 0.0, a1 = 0.0, x1 = 0.0, y1 = 0.0;

  void set(double hz, double gainDb, Side side) {
    const double v = std::pow(10.0, gainDb / 20.0);
    const double k = std::tan(kPi * hz / kSampleRateHz);
    const double norm = 1.0 / (1.0 + k);
    a1 = (k - 1.0) * norm;
    if (side == Side::Low) {
      b0 = (1.0 + v * k) * norm;
      b1 = (v * k - 1.0) * norm;
    } else {
      b0 = (v + k) * norm;
      b1 = (k - v) * norm;
    }
  }

  double process(double x) {
    const double y = b0 * x + b1 * x1 - a1 * y1;
    x1 = x;
    y1 = y;
    return y;
  }
};`,

  biquad: `/** A second-order section, set the way the audio cookbook sets one. */
struct Biquad {
  enum class Side { Low, High };

  double b0 = 1.0, b1 = 0.0, b2 = 0.0, a1 = 0.0, a2 = 0.0;
  double x1 = 0.0, x2 = 0.0, y1 = 0.0, y2 = 0.0;

  void setShelf(double hz, double gainDb, Side side) {
    const double a = std::pow(10.0, gainDb / 40.0);
    const double w = 2.0 * kPi * hz / kSampleRateHz;
    const double cs = std::cos(w);
    // Unit slope, which is what \`order 2\` means here.
    const double alpha = std::sin(w) / 2.0 * std::sqrt(2.0);
    const double two = 2.0 * std::sqrt(a) * alpha;
    const double sign = side == Side::Low ? 1.0 : -1.0;
    const double a0 = (a + 1.0) - sign * (a - 1.0) * cs + two;
    b0 = a * ((a + 1.0) + sign * (a - 1.0) * cs + two) / a0;
    b1 = sign * 2.0 * a * ((a - 1.0) + sign * (a + 1.0) * cs) / a0;
    b2 = a * ((a + 1.0) + sign * (a - 1.0) * cs - two) / a0;
    a1 = -sign * 2.0 * ((a - 1.0) - sign * (a + 1.0) * cs) / a0;
    a2 = ((a + 1.0) - sign * (a - 1.0) * cs - two) / a0;
  }

  void setPeaking(double hz, double gainDb, double q) {
    const double a = std::pow(10.0, gainDb / 40.0);
    const double w = 2.0 * kPi * hz / kSampleRateHz;
    const double alpha = std::sin(w) / (2.0 * q);
    const double a0 = 1.0 + alpha / a;
    b0 = (1.0 + alpha * a) / a0;
    b1 = -2.0 * std::cos(w) / a0;
    b2 = (1.0 - alpha * a) / a0;
    a1 = b1;
    a2 = (1.0 - alpha / a) / a0;
  }

  double process(double x) {
    const double y = b0 * x + b1 * x1 + b2 * x2 - a1 * y1 - a2 * y2;
    x2 = x1;
    x1 = x;
    y2 = y1;
    y1 = y;
    return y;
  }
};`,
};

